"""Render evaluation results as markdown."""

from __future__ import annotations

import datetime as dt
import os
import platform
import sys
from collections.abc import Sequence
from dataclasses import dataclass

import numpy as np

from rag_eval_kit.answer.extractive import DEFAULT_MIN_COVERAGE, DEFAULT_MIN_GAIN
from rag_eval_kit.eval.harness import RECALL_KS, AnswerReport, RetrievalReport


@dataclass
class JudgeSummary:
    """Aggregate LLM-judge results, or the reason the judge did not run."""

    ran: bool
    note: str
    n: int = 0
    mean_score: float = float("nan")
    faithful_rate: float = float("nan")


def environment() -> dict[str, str]:
    """Machine and runtime details recorded alongside the numbers."""
    return {
        "date": dt.datetime.now(dt.UTC).strftime("%Y-%m-%d"),
        "os": platform.platform(),
        "cpu": f"{platform.processor() or platform.machine()} ({os.cpu_count()} logical cores)",
        "python": sys.version.split()[0],
        "numpy": np.__version__,
    }


def _f(x: float) -> str:
    return "n/a" if x != x else f"{x:.3f}"


def _ms(x: float) -> str:
    return "n/a" if x != x else f"{x:.2f}"


def retrieval_table(rows: Sequence[tuple[str, RetrievalReport]]) -> str:
    """Markdown table of retrieval metrics, one row per (chunker, retriever)."""
    header = (
        "| chunker | retriever | "
        + " | ".join(f"Recall@{k}" for k in RECALL_KS)
        + " | MRR | nDCG@10 | multi-hop full recall@5 | p50 ms | p95 ms |"
    )
    sep = "|" + "---|" * (2 + len(RECALL_KS) + 5)
    lines = [header, sep]
    for chunker, r in rows:
        recalls = " | ".join(_f(r.recall[k]) for k in RECALL_KS)
        lines.append(
            f"| {chunker} | {r.name} | {recalls} | {_f(r.mrr)} | {_f(r.ndcg10)} | "
            f"{_f(r.multi_hop_full_recall5)} | {_ms(r.latency_p50_ms)} | {_ms(r.latency_p95_ms)} |"
        )
    return "\n".join(lines)


def answer_table(rows: Sequence[AnswerReport]) -> str:
    """Markdown table of answer metrics, one row per (retriever, answerer)."""
    lines = [
        "| retriever + answerer | token F1 | answer recall | citation precision | "
        "refusal accuracy (unanswerable) | false refusal rate (answerable) | p50 ms | p95 ms |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r.name} | {_f(r.f1)} | {_f(r.answer_recall)} | {_f(r.citation_precision)} | "
            f"{_f(r.refusal_accuracy)} | {_f(r.false_refusal_rate)} | "
            f"{_ms(r.latency_p50_ms)} | {_ms(r.latency_p95_ms)} |"
        )
    return "\n".join(lines)


def sweep_table(rows: Sequence[AnswerReport]) -> str:
    """Markdown table of extractive-answerer settings and their trade-offs."""
    lines = [
        "| setting | refusal accuracy | false refusal rate | token F1 | answer recall | citation precision |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r.name} | {_f(r.refusal_accuracy)} | {_f(r.false_refusal_rate)} | {_f(r.f1)} | "
            f"{_f(r.answer_recall)} | {_f(r.citation_precision)} |"
        )
    return "\n".join(lines)


def render(
    retrieval: Sequence[tuple[str, RetrievalReport]],
    answers: Sequence[AnswerReport],
    sweep: Sequence[AnswerReport],
    judge: JudgeSummary,
    dataset_summary: str,
    command: str,
    k: int,
) -> str:
    """Assemble the full ``RESULTS.md`` document."""
    env = environment()
    env_lines = "\n".join(f"- **{key}**: {value}" for key, value in env.items())
    if judge.ran:
        judge_text = (
            f"Claude judged {judge.n} answers: mean faithfulness score {judge.mean_score:.2f}/5, "
            f"faithful rate {judge.faithful_rate:.3f}. {judge.note}"
        )
    else:
        judge_text = f"Not run. {judge.note}"
    return f"""# Evaluation results

Generated by `{command}`.

{env_lines}

**Dataset:** {dataset_summary}

## Retrieval

Metrics over answerable questions. Recall@k = share of gold evidence quotes found in the top
k chunks (a multi-hop question needs every hop); MRR and nDCG@10 use binary chunk relevance
(a chunk is relevant if it contains a gold evidence quote). Latency is per query, in-process.

{retrieval_table(retrieval)}

## Answering (offline baseline unless stated)

Heading-aware chunks, top {k} retrieved chunks per question. Token F1 and answer recall
compare against short gold answers (refusals score 0). Citation precision = share of cited
chunks from a gold document. Latency covers retrieval + answering.

{answer_table(answers)}

### Extractive answerer parameter sweeps (hybrid retrieval)

`min_coverage`: the answerer refuses when the top 3 chunks cover less than this share of the
question's IDF-weighted terms (default {DEFAULT_MIN_COVERAGE}). `min_gain`: a second sentence is
added only if it covers at least this share of the still-uncovered question weight (default
{DEFAULT_MIN_GAIN}; 1.01 means "always one sentence"). Defaults were chosen by looking at these
sweeps on the same question set, so they are dev-set numbers, not held-out ones.

{sweep_table(sweep)}

## LLM-as-judge faithfulness

{judge_text}
"""
